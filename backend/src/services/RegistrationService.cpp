// Approximates PHP's FILTER_VALIDATE_EMAIL for the shapes this form accepts.
bool isValidEmail(const std::string& email) {
    const std::size_t at = email.find('@');
    if (at == std::string::npos || at == 0 || at + 1 >= email.size()) {
        return false;
    }
    if (email.find('@', at + 1) != std::string::npos) {
        return false;
    }
    const std::string domain = email.substr(at + 1);
    const std::size_t dot = domain.find('.');
    if (dot == std::string::npos || dot == 0 || dot + 1 >= domain.size()) {
        return false;
    }
    for (const char c : email) {
        if (std::isspace(static_cast<unsigned char>(c))) {
            return false;
        }
    }
    return true;
}

bool isSixDigits(const std::string& value) {
    if (value.size() != 6) {
        return false;
    }
    for (const char c : value) {
        if (!std::isdigit(static_cast<unsigned char>(c))) {
            return false;
        }
    }
    return true;
}

json::Value failure(const std::string& message, const std::string& kind = std::string()) {
    json::Value out = json::Value::object();
    out.set("success", json::Value(false));
    out.set("error", json::Value(message));
    if (!kind.empty()) {
        out.set("error_kind", json::Value(kind));
    }
    return out;
}

